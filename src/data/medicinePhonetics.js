/** Payload sent on STOP — aliases include primary Sinhala phonetic + extras. */
export function getMedicineStopPayload() {
  return RAW.map(({ name, phoneticSinhala, category, categoryPhoneticSinhala, aliases }) => {
    const allAliases = [phoneticSinhala, ...(aliases ?? [])]
      .map((a) => a?.trim())
      .filter(Boolean);
    return {
      name,
      phoneticSinhala,
      category,
      categoryPhoneticSinhala,
      aliases: [...new Set(allAliases)],
    };
  });
}

